  function normalize(locale) { return locale === 'en-US' ? 'en-US' : 'zh-CN'; }
  function format(value, params) {
    return String(value).replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, function (match, key) {
      return params && Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match;
    });
  }
  function t(source, locale, params) {
    var key = String(source);
    return format(normalize(locale) === 'en-US' && Object.prototype.hasOwnProperty.call(english, key)
      ? english[key] : key, params);
  }
  function has(source) { return Object.prototype.hasOwnProperty.call(english, String(source)); }
  return Object.freeze({ normalize: normalize, t: t, has: has, english: english });
